// ToolCall represents an action invoked by the model.
type ToolCall struct {
	ID   string         `json:"id"`
	Tool string         `json:"tool"`
	Args map[string]any `json:"args"`
}

// A2AProposal represents a proposed negotiation sent to another peer's Selfvoy.
type A2AProposal struct {
	Target  string         `json:"target"`
	Intent  string         `json:"intent"`
	Topic   string         `json:"topic"`
	Slots   []planner.Slot `json:"slots"`
	Place   map[string]any `json:"place,omitempty"`
	Message string         `json:"message"`
}

// AgentContext holds all contextual information passed from the main C++ server.
type AgentContext struct {
	UserID      int                     `json:"user_id"`
	DisplayName string                  `json:"display_name"`
	Email       string                  `json:"email"`
	Now         *time.Time              `json:"now,omitempty"`
	Timezone    string                  `json:"timezone"`
	Message     string                  `json:"message"`
	History     []map[string]any        `json:"history,omitempty"`
	Memory      []memory.MemoryEntry    `json:"memory,omitempty"`
	Preferences planner.Preferences     `json:"preferences"`
	Calendar    []planner.CalendarEvent `json:"calendar,omitempty"`
	Contacts    []map[string]any        `json:"contacts,omitempty"`
}

// LLMPayload is the structured response generated by an LLM or fallback rules.
type LLMPayload struct {
	Reply         string               `json:"reply"`
	Intent        string               `json:"intent"`
	Confidence    float64              `json:"confidence"`
	Actions       []ToolCall           `json:"actions"`
	MemoryUpdates []memory.MemoryEntry `json:"memory_updates"`
	A2A           *A2AProposal         `json:"a2a,omitempty"`
}

// Client defines the LLM completion interface.
type Client interface {
	Name() string
	CompleteJSON(ctx context.Context, agentCtx *AgentContext, understanding *planner.Understanding) (*LLMPayload, error)
}
